export type IpcChannel = (typeof IPC_CHANNELS)[number]

/** Prefix applied to every channel on the wire so app channels never collide with Electron internals. */
export const IPC_PREFIX = 'sa-erp:'

export function isIpcChannel(value: unknown): value is IpcChannel {
  return typeof value === 'string' && (IPC_CHANNELS as readonly string[]).includes(value)
}
